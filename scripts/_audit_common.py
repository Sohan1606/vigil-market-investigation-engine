"""Shared machinery for scripts/self_audit.py and scripts/release_audit.py.

Four states, and the difference between the last two matters:

    PASS          the property was checked and holds
    PARTIAL       the property holds only in part, with the gap named
    FAIL          the property was checked and does not hold
    NOT EXECUTED  the check could not run here (infrastructure absent, optional tool missing).
                  Never silently upgraded to PASS — "we could not test this" is a distinct,
                  visible outcome.
"""
from __future__ import annotations

import json
import os
import re
import shutil
import subprocess
import sys
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional

ROOT = Path(__file__).resolve().parents[1]
RESULTS = ROOT / "reports" / "results"

PASS = "PASS"
PARTIAL = "PARTIAL"
FAIL = "FAIL"
NOT_EXECUTED = "NOT EXECUTED"
STATES = (PASS, PARTIAL, FAIL, NOT_EXECUTED)


@dataclass
class Row:
    category: str
    check: str
    state: str
    evidence: str


@dataclass
class Recorder:
    rows: List[Row] = field(default_factory=list)

    def add(self, category: str, check: str, state: str, evidence: str) -> None:
        if state not in STATES:
            raise ValueError(f"invalid audit state {state!r}")
        # Evidence is quoted verbatim into a committed report, so the repo root — which differs on
        # every machine — is rewritten to a relative marker before it can be baked in.
        text = str(evidence).replace(str(ROOT) + "/", "./").replace(str(ROOT), ".")
        self.rows.append(Row(category, check, state, text))

    def counts(self) -> Dict[str, int]:
        return {s: sum(1 for r in self.rows if r.state == s) for s in STATES}

    def exit_code(self) -> int:
        """FAIL is fatal. NOT EXECUTED is reported, not fatal — it is honest, not broken."""
        return 1 if self.counts()[FAIL] else 0

    def markdown(self, title: str, generated_by: str, timestamp: str,
                 extra: Optional[List[str]] = None) -> str:
        c = self.counts()
        lines = [f"# {title}", "",
                 f"_Generated by `{generated_by}` on {timestamp}._", "",
                 f"**{c[PASS]} PASS · {c[PARTIAL]} PARTIAL · {c[FAIL]} FAIL · "
                 f"{c[NOT_EXECUTED]} NOT EXECUTED**", "",
                 "`NOT EXECUTED` means the check could not run in this environment (for example no "
                 "Hadoop cluster or no browser). It is never counted as a pass.", "",
                 "| Category | Check | Result | Evidence |", "|---|---|---|---|"]
        for r in self.rows:
            ev = r.evidence.replace("|", "\\|").replace("\n", " ")
            lines.append(f"| {r.category} | {r.check} | **{r.state}** | {ev} |")
        if extra:
            lines += [""] + extra
        return "\n".join(lines) + "\n"

    def to_json(self) -> Dict[str, Any]:
        return {"counts": self.counts(),
                "rows": [{"category": r.category, "check": r.check, "state": r.state,
                          "evidence": r.evidence} for r in self.rows]}

    def print_summary(self) -> None:
        for r in self.rows:
            print(f"{r.state:13} {r.category}: {r.check}")
        print(f"\n{self.counts()}")


# --------------------------------------------------------------------------- loading
def load_result(name: str) -> Optional[dict]:
    p = RESULTS / name
    if not p.exists():
        return None
    try:
        return json.loads(p.read_text())
    except json.JSONDecodeError:
        return None


def read_text(path: Path) -> str:
    try:
        return path.read_text(errors="ignore")
    except Exception:
        return ""


